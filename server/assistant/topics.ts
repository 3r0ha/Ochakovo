/** Тема вопроса по словарю; null — словарь тему не узнал */
export function gapTopic(question: string): string | null {
  const t = question.toLowerCase().replace(/ё/g, 'е')
  return DICTIONARY.find(([re]) => re.test(t))?.[1] ?? null
}
