/** Сколько карточек в одной игре */
export const DECK_SIZE = 5
/** Состав колоды: столько карточек про работу, остальные — про историю */
export const DECK_WORK = 3
/** В колоде не меньше стольких правд и стольких мифов — чтобы не угадывалось «везде миф» */
export const DECK_MIN_EACH = 2

/** Все сочетания по k элементов из списка, в исходном порядке */
function combinations<T>(list: T[], k: number): T[][] {
  if (k === 0) return [[]]
  if (list.length < k) return []
  const [head, ...rest] = list
  return [...combinations(rest, k - 1).map((c) => [head, ...c]), ...combinations(rest, k)]
}

/** Подходящие колоды без учёта порядка: 3 про работу + 2 про историю, правд и мифов не меньше чем по 2 */
const validHands: MythCard[][] = (() => {
  const work = myths.filter((m) => m.topic === 'work')
  const history = myths.filter((m) => m.topic === 'history')
  const out: MythCard[][] = []
  for (const w of combinations(work, DECK_WORK))
    for (const h of combinations(history, DECK_SIZE - DECK_WORK)) {
      const hand = [...w, ...h]
      const truths = hand.filter((m) => m.truth).length
      if (truths >= DECK_MIN_EACH && hand.length - truths >= DECK_MIN_EACH) out.push(hand)
    }
  return out
})()

/**
 * Колода на одну игру: 3 карточки про работу и 2 про историю, не меньше 2 правд и 2 мифов, порядок случайный.
 * Каждое подходящее сочетание выпадает с равной вероятностью. rng — для повторяемых проверок
 */
export function buildDeck(rng: () => number = Math.random): MythCard[] {
  const pick = (n: number) => Math.min(n - 1, Math.floor(rng() * n))
  const deck = [...validHands[pick(validHands.length)]]
  for (let i = deck.length - 1; i > 0; i--) {
    const j = pick(i + 1)
    ;[deck[i], deck[j]] = [deck[j], deck[i]]
  }
  return deck
}

