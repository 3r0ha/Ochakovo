/**
 * Зачем проходить: за COMPANY_QUIZ_PASS верных из раунда — значок «1978» из коллекции мерча «Смена»
 * (docs/brand/merch.md). Его же дают за контрольные вопросы на экскурсии и в музее. Результат уходит в заявку,
 * HR видит его в карточке и выдаёт значок в первый день, если его не забрали раньше
 */
export const COMPANY_QUIZ_PASS = 6
export const COMPANY_QUIZ_REWARD = 'значок «1978»'
export const companyQuizPassed = (score: number, total: number) => total > 0 && score >= Math.min(COMPANY_QUIZ_PASS, total)

/** Обещание до старта: что получишь и куда пойдёт результат */
export const companyQuizPromise = () =>
  `Ответь верно на ${COMPANY_QUIZ_PASS} из ${COMPANY_QUIZ_ROUND}, и получишь ${COMPANY_QUIZ_REWARD}. Результат попадёт в заявку.`

/** Где забрать значок. on — «этот экран» на сайте или «это сообщение» в боте */
export const companyQuizRewardWhere = (on: 'screen' | 'message') =>
  `Покажи ${on === 'screen' ? 'этот экран' : 'это сообщение'} на стенде «Очаково» на ярмарке или на экскурсии. Если подашь заявку, значок выдадут в первый день.`

/** Итог одной фразой: «5 из 7» и что дальше. Нейтральный род, без «!» */
export function companyQuizResult(score: number, total: number): string {
  const pass = Math.min(COMPANY_QUIZ_PASS, total)
  if (score === total) return `${score} из ${total}, все ответы верные. ${upper(COMPANY_QUIZ_REWARD)} твой.`
  if (score >= pass) return `${score} из ${total}. ${upper(COMPANY_QUIZ_REWARD)} твой.`
  const left = pass - score
  return `${score} из ${total}. До значка не хватило ${left} ${left === 1 ? 'верного ответа' : 'верных ответов'}, попробуй ещё раз: вопросы будут другие.`
}

const upper = (t: string) => t.charAt(0).toUpperCase() + t.slice(1)
