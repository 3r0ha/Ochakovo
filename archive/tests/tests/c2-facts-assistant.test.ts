// Квасыч знает официальные факты: база знаний (server/assistant/knowledge.ts) и фактические строки офлайн-режима
// (server/llm/offline.ts) — те же, что в shared/content. Автобус, общежитие, наставник, зарплата 12-го и 27-го,
// документы по практике, бренды без алкоголя. Ответы проходят проверку guard, а не падают в «спроси в отделе персонала».
// Запуск: pnpm test c2-facts-assistant (без базы)

import assert from 'node:assert/strict'
import { test } from 'node:test'
import { createAssistant } from '../../server/assistant/assistant'
import { chunks, knowledgeText } from '../../server/assistant/knowledge'
import { offlineProvider } from '../../server/llm/offline'
import { contacts } from '../../shared/content/content'
import { vacancies } from '../../shared/content/vacancies'

const plain = (t: string) => t.replace(/[  ]/g, ' ').replace(/⁠/g, '')
const assistant = createAssistant({ provider: offlineProvider(), log: () => {} })
const ask = async (question: string) => plain((await assistant.answer({ question, history: [], sessionId: 'c2-facts', channel: 'web' })).text)
const SAFE = /Здесь лучше ответит отдел персонала, чтобы не ошибиться/

test('база знаний: официальные факты есть, старых решений и технических id нет', () => {
  const kb = plain(knowledgeText())
  for (const part of [
    contacts.shuttle,
    'корпоративный автобус',
    '3 400 ₽ за койко-место',
    '12-го и 27-го',
    'К каждому новичку прикрепляют наставника',
    'У студентов испытательного срока нет',
    'кабинет 525',
    'Учебный центр: 8 800 100-77-77, доб. 1244 или 3105',
    'Здравпункт: 8 800 100-77-77, доб. 1370 или 1303',
    'от 56 000 ₽ до 70 000 ₽',
    'Бесплатная практика по договорённости',
    'квас «Очаковский» и «Семейный секрет»',
    'Натуральные — значит настоящие',
    'Олимпиад',
  ])
    assert.ok(kb.includes(part), `в базе нет «${part}»`)
  for (const bad of [/Полис ДМС для сотрудников/, /Свободные места и стоимость — у HR/, /В вакансиях «Очаково» указан и корпоративный транспорт/, /107 000/, /экскурсовод/i, /ориентир/i])
    assert.doesNotMatch(kb, bad)
  for (const v of vacancies) assert.ok(!kb.includes(v.id), `технический id ${v.id} в базе`)
  assert.equal(new Set(chunks.map((c) => c.id)).size, chunks.length, 'id фрагментов не повторяются')
})

test('офлайн-Квасыч: дорога — корпоративный автобус первым', async () => {
  for (const q of ['есть корпоративный автобус?', 'как добраться от метро', 'есть развозка?']) {
    const a = await ask(q)
    assert.doesNotMatch(a, SAFE, q)
    assert.match(a, /корпоративный автобус/, `${q}: ${a.slice(0, 200)}`)
    assert.match(a, /610 и 807/)
  }
})

test('офлайн-Квасыч: справочник студента — прямые ответы', async () => {
  const cases: [string, RegExp][] = [
    ['есть испытательный срок?', /испытательного срока нет/],
    ['кто будет учить?', /наставник/i],
    ['когда зарплата?', /12-го и 27-го/],
    ['какие документы для практики', /Учебный центр, кабинет 525/],
    ['сколько стоит общежитие', /койко-место стоит 3 400 ₽/],
    ['есть общага?', /Рябиновая, 36, к\. 2/],
    ['обед есть?', /Половину стоимости компенсирует компания/],
    ['где учебный центр', /доб\. 1244 или 3105/],
    ['можно практику от вуза?', /от 56 000 до 70 000 ₽/],
    ['а стажировки есть?', /Оплачиваемая практика/],
    ['есть ДМС?', /ДМС не указан/],
    ['что делает лаборант', /органолептические анализы/],
    ['сколько платят кладовщику', /от 56 000 ₽/],
    ['сессия в июне, можно?', /смены на это время не ставят/],
    ['какие бренды', /квас «Очаковский» и «Семейный секрет»/],
    ['расскажи про очаково', /лидирует на рынке натурального кваса/],
    ['кто ты', /^Я Квасыч/],
  ]
  for (const [q, want] of cases) {
    const a = await ask(q)
    assert.doesNotMatch(a, SAFE, `${q}: ответ отклонила проверка`)
    assert.match(a, want, `${q}: ${a.slice(0, 240)}`)
    assert.ok(!a.includes('!'), `«!» в ответе на «${q}»`)
  }
})

test('офлайн-Квасыч: нет старых фактов — экскурсовода, стажировок с ориентиром, «часть стоимости», «стоимость у HR»', async () => {
  for (const q of ['сколько получает экскурсовод', 'какие вакансии есть', 'я студент, хочу подработку', 'чем лучше кофейни', 'есть общага?', 'сколько платят?']) {
    const a = await ask(q)
    for (const bad of [/на экскурсиях/, /стажировки с ориентиром|это ориентир/, /часть стоимости оплачивает завод/, /стоимость — у HR/, /107 000/, /конвейерной линии/])
      assert.doesNotMatch(a, bad, `${q}: ${a.slice(0, 200)}`)
  }
  assert.match(await ask('сколько получает экскурсовод'), /^Вакансии «экскурсовод» нет/)
})
