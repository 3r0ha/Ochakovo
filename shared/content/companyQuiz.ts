/** Сколько вопросов в одном прохождении */
export const COMPANY_QUIZ_ROUND = 7

/** Вопрос раунда: варианты перемешаны, answer указывает на правильный в новом порядке */
export type CompanyQuizRoundItem = CompanyQuizQuestion & { order: number[] }

/**
 * Раунд: size случайных вопросов без повторов, варианты в каждом перемешаны. order — исходные индексы вариантов в новом порядке
 * (для кнопок бота cq:<id>:<исходный индекс>). rng — для повторяемых проверок
 */
export function companyQuizRound(rng: () => number = Math.random, size = COMPANY_QUIZ_ROUND): CompanyQuizRoundItem[] {
  const pick = (n: number) => Math.min(n - 1, Math.floor(rng() * n))
  const shuffle = <T>(list: T[]): T[] => {
    const out = [...list]
    for (let i = out.length - 1; i > 0; i--) {
      const j = pick(i + 1)
      ;[out[i], out[j]] = [out[j], out[i]]
    }
    return out
  }
  return shuffle(companyQuiz)
    .slice(0, Math.max(1, Math.min(size, companyQuiz.length)))
    .map((q) => {
      const order = shuffle(q.options.map((_, i) => i))
      return { ...q, options: order.map((i) => q.options[i]), answer: order.indexOf(q.answer), order }
    })
}

