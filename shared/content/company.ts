/** Бренды одной строкой: «квас «Очаковский» и «Семейный секрет», «Очаковский лимонад», CoolCola …» */
export const brandsLine = (() => {
  const kvass = brands.filter((b) => b.kind === 'квас').map((b) => b.name)
  const rest = brands.filter((b) => b.kind !== 'квас').map((b) => `${b.name} (${b.kind})`)
  return `квас ${kvass.join(' и ')}, ${rest.join(', ')}`
})()

