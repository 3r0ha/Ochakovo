/** Слова названий вакансий без «е/ё» и регистра: «конвейерной», «брожения», «мерчандайзер».
 *  «Стажёр» не берём: «со стажем» на одну правку от него, а это обычные слова */
const TITLE_VOCAB = vacancies.flatMap((v) => v.title.toLowerCase().replace(/ё/g, 'е').match(/[а-я]{5,}/g) ?? []).filter((w) => w !== 'стажер')

const VOCAB = [...new Set([...WORK_VOCAB, ...PLACE_VOCAB, ...TITLE_VOCAB])]
const VOCAB_SET = new Set(VOCAB)

/** Расстояние Дамерау — Левенштейна не больше одного: замена, вставка, удаление или перестановка соседних букв */
export function oneEditApart(a: string, b: string): boolean {
  if (a === b) return false
  const la = a.length
  const lb = b.length
  if (Math.abs(la - lb) > 1) return false
  if (la === lb) {
    const diff: number[] = []
    for (let i = 0; i < la && diff.length <= 2; i++) if (a[i] !== b[i]) diff.push(i)
    if (diff.length === 1) return true
    return diff.length === 2 && diff[1] === diff[0] + 1 && a[diff[0]] === b[diff[1]] && a[diff[1]] === b[diff[0]]
  }
  const [short, long] = la < lb ? [a, b] : [b, a]
  let i = 0
  while (i < short.length && short[i] === long[i]) i++
  return short.slice(i) === long.slice(i + 1)
}

/**
 * Опечатки: слово от 6 букв, которого нет в словаре и которое не узнают правила (known),
 * меняем на слово базы на расстоянии одной правки. Только если кандидат один — по корню, а не по окончанию:
 * «зарплатв» близко и к «зарплата», и к «зарплату», но корень у них общий. Слова с цифрами не трогаем
 */
export function fixTypos(text: string, known: (word: string) => boolean): string {
  return text.replace(/[а-я]{6,}/g, (word) => {
    if (VOCAB_SET.has(word) || known(word)) return word
    const near = VOCAB.filter((v) => oneEditApart(word, v))
    if (!near.length) return word
    const roots = new Set(near.map(stem))
    return roots.size === 1 ? near[0] : word
  })
}

/** Разговорное и опечатки — к словам, которые понимают правила офлайн-режима */
export function normalize(question: string, known: (word: string) => boolean = () => false): string {
  let t = question.toLowerCase().replace(/ё/g, 'е')
  for (const [re, to] of SLANG) t = t.replace(re, to)
  t = t.replace(/\s+/g, ' ').trim()
  return fixTypos(t, known)
}

// ── «Привет», «спасибо», «ок» в начале ─────────────────────────────────

export type Lead = 'hello' | 'thanks' | 'ok'

const LEADS: [RegExp, Lead][] = [
  [/^(привет(ик|ствую)?|здравству(й|йте)|добр(ый|ое|ого)\s+(день|вечер|утро|дня|вечера|утра)|доброе утро|хай|хеллоу|hello|hi|салют|здарова|здорово)(?![а-яa-z])/, 'hello'],
  [/^(спасибо(\s+большое)?|спс|благодарю|благодарствую)(?![а-яa-z])/, 'thanks'],
  [/^(ок(ей)?|окей|ok|okay|понятно|ясно|хорошо|ладно|ага|угу|супер|отлично|класс|круто|понял|поняла)(?![а-яa-z])/, 'ok'],
  // Обращение по имени: «квасыч, сколько платят»
  [/^квасыч(?=\s*[,!.—-])/, 'ok'],
]

/**
 * Отрезает вежливое начало: «привет, сколько платят?» → «сколько платят?».
 * lead — что отрезали первым: на одно «привет» без вопроса отвечаем приветствием
 */
export function stripLead(text: string): { rest: string; lead: Lead | null } {
  // Регистр исходного текста сохраняем: по заглавной букве после точки вопрос делится на части
  let rest = text.trim()
  let lead: Lead | null = null
  for (let guard = 0; guard < 4; guard++) {
    const lower = rest.toLowerCase().replace(/ё/g, 'е')
    const hit = LEADS.map(([re, kind]) => [re.exec(lower), kind] as const).find(([m]) => m)
    if (!hit?.[0]) break
    lead ??= hit[1]
    rest = rest.slice(hit[0][0].length).replace(/^[\s,.!?;:—–-]+/, '')
  }
  return { rest: rest.trim(), lead }
}

// ── Вопрос из нескольких частей ─────────────────────────────────────────

/** Вопросительное слово — признак того, что часть после запятой — отдельный вопрос */
const QUESTION_WORD =
  /(?<![а-я])(сколько|где|как|когда|какой|какая|какое|какие|каким|какую|можно|есть|нужн[аоы]?|берут|кто|что|чем|почему|зачем|куда|откуда|бывает|бывают|дают|платят)(?![а-я])/

/** «хочу с другом в одну смену, и общага платная?» → две части; «сколько платят, где жить» — тоже две */
export function splitParts(question: string): string[] {
  return question
    .split(
      /\?\s*|;\s*|,\s*(?:и|а|а ещ[её]|и ещ[её]|ещ[её])\s+|\.\s+(?=[А-ЯЁA-Z])|\s+а\s+ещ[её]\s+|\s+и\s+(?=(?:можно|есть|как|где|когда|какой|какая|какие|нужн[аоы]?|берут|реально|получится|сколько|кто|что|чем|почему|зачем)(?![а-яё]))/i,
    )
    .flatMap((part) => {
      // Запятая делит, только если в каждой половине свой вопрос: «скока на руки без опыта, мне 18» — один вопрос
      const pieces = part.split(/,\s*/)
      return pieces.length > 1 && pieces.every((p) => QUESTION_WORD.test(p.toLowerCase())) ? pieces : [part]
    })
    .map((p) => p.trim())
    .filter((p) => p.split(/\s+/).length >= 2)
}
