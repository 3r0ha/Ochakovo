/** «меня зовут Аня», «я Аня», «это Аня» → «Аня». Остальное — как есть */
export function stripNameIntro(text: string) {
  return text
    .trim()
    .replace(/^(меня\s+зовут|мо[её]\s+имя|зовут|я\s*[—–-]|я|это)\s+/i, '')
    .replace(/[.!,;]+$/, '')
    .trim()
}

/**
 * Похоже на вопрос, а не на ответ шага: знак вопроса, вопросительное слово в начале,
 * тема помощника целым словом или больше пяти слов.
 * strict — для шагов, где ждём свободный текст (портфолио, имя друга): только «?» и вопросительное слово в начале,
 * иначе «мои работы в телеграме» ушло бы помощнику
 */
export function looksLikeQuestion(text: string, strict = false) {
  if (text.includes('?')) return true
  const t = norm(stripNameIntro(text))
  const w = words(t)
  if (!w.length) return false
  if (QUESTION_START.has(w[0])) return true
  if (strict) return false
  if (w.some((x) => TOPIC_WORDS.has(x))) return true
  return w.length > 5
}

/** Имя похоже на имя: буквы, дефис, апостроф, пробел; от 2 до 80 знаков и не больше пяти слов */
export function asName(text: string): string | null {
  const clean = stripNameIntro(text).replace(/\s+/g, ' ').trim().slice(0, 80)
  if (clean.length < 2 || !/^[a-zа-яё][a-zа-яё' -]*$/i.test(clean) || clean.split(' ').length > 5) return null
  // Набрано строчными — поднимаем первые буквы: «анна-мария» → «Анна-Мария»
  return clean === clean.toLowerCase() ? clean.replace(/(^|[\s-])([a-zа-яё])/g, (_, sep: string, ch: string) => sep + ch.toUpperCase()) : clean
}

/** «Хочу откликнуться», «оставить заявку», «запиши меня», «где заявку оставить» — открыть заявку */
export function wantsToApply(text: string) {
  const t = norm(text)
  return /(^|[^а-я])(хочу|можно|как|где)\s+(бы\s+)?откликнуться|(оставить|подать|отправить|заполнить)\s+заявк|заявк[уа]\s+(оставить|подать|отправить|заполнить)|запиши(те)?\s+меня/.test(t)
}

/** «Можно без телефона?», «не хочу давать номер» — человеку удобнее ник */
export function refusesPhone(text: string) {
  const t = norm(text)
  return /без\s+(телефона|номера)|не\s+(хочу|буду|могу)\s+(давать\s+|оставлять\s+|писать\s+)?(свой\s+)?(телефон|номер)|не\s+(дам|оставлю)\s+(свой\s+)?(телефон|номер)|нет\s+(телефона|номера)|(телефон|номер)\s+не\s+(дам|хочу|оставлю)/.test(
    t,
  )
}

/** Ответ на «Тебе есть 18 лет?»: да, нет или не понять */
export function parseAdult(text: string): 'yes' | 'no' | null {
  const t = norm(text).replace(/[.!,]+$/g, '')
  const age = /(^|[^0-9])(1[0-9]|[2-9][0-9])\s*(лет|год|года)?$/.exec(t)
  if (age && /^(мне\s+)?(уже\s+)?\d{2}(\s*(лет|год|года))?$/.test(t)) return Number(age[2]) >= 18 ? 'yes' : 'no'
  if (/^(да|ага|угу|есть|конечно|да,?\s*есть|да,?\s*уже|уже есть|исполнилось|да,?\s*исполнилось|yes)$/.test(t)) return 'yes'
  if (/^(нет|неа|не|нету|еще нет|пока нет|нет,?\s*еще нет|не исполнилось|no)$/.test(t)) return 'no'
  return null
}
