// Слова вопроса для поиска: нижний регистр, «е» вместо «ё», без общих слов, основы вместо словоформ.
// Общий модуль для основной базы знаний (knowledge.ts) и маленького индекса ответов HR (hrAnswers.ts)

/** Окончания, которые срезаем, чтобы «общежитие», «общежития» и «общежитии» совпали.
 *  -ат и -ят не срезаем: иначе «формат» и «форму» становятся одним словом */
const endings = [
  'иями', 'ями', 'ами', 'ого', 'его', 'ому', 'ему', 'ыми', 'ими', 'иях', 'ией',
  'ия', 'ие', 'ии', 'ий', 'ой', 'ый', 'ая', 'яя', 'ое', 'ее', 'ую', 'юю', 'ом', 'ем', 'ам', 'ям', 'ах', 'ях',
  'ов', 'ев', 'ей', 'ть', 'ти', 'ет', 'ит', 'ут', 'ют', 'им', 'ла', 'ло', 'ли',
  'а', 'я', 'о', 'е', 'и', 'ы', 'у', 'ю', 'ь',
]

/** Синонимы приводим к одному корню: «общага» и «общежитие», «зарплата» и «платят» */
const synonyms: [RegExp, string][] = [
  [/^(общаг|общежит|жиль|прожив|жить|живут)/, 'общежит'],
  [/^(зарплат|плат|оплат|зараб|деньг|получа|оклад|ставк)/, 'плат'],
  [/^(лаборат|лаборант|анализ)/, 'лаборатор'],
  [/^(вар|сусл)/, 'варк'],
  [/^(брож|заквас)/, 'брожен'],
  [/^(добрат|доеха|доехат|ехат|метро|автобус|адрес|дорог|развоз|шаттл|трансфер)/, 'дорог'],
  [/^(настав|обучат|обучен)/, 'наставник'],
  [/^(столов|обед|питан|ужин|еда|еды)/, 'столов'],
  [/^(экзамен|сесси|зачет|зачёт)/, 'экзамен'],
  [/^(склад|кладовщ|отгруз)/, 'склад'],
  [/^(опыт)/, 'опыт'],
  [/^(ночн|ночь|график|смен)/, 'график'],
  [/^(лет|сезон|месяц)/, 'срок'],
  [/^(устро|отклик|заявк|собеседов|оформ|медкомис)/, 'устро'],
  [/^(парков|паркинг|припарков)/, 'парковк'],
  [/^(здравпункт|медпункт|медсестр|врач)/, 'здравпункт'],
  [/^(прачечн|стирк|стират|постират)/, 'прачечн'],
  [/^(спецодеж|спецовк|униформ|форм[аеуы]$)/, 'спецодеж'],
]

/** Общие слова не должны решать, какой фрагмент ответит: «можно», «как», «есть», «а» есть почти в любом вопросе */
const stop = new Set([
  'а', 'и', 'но', 'я', 'ты', 'вы', 'мы', 'он', 'она', 'они', 'мне', 'меня', 'мой', 'моя', 'ваш', 'вас', 'вам', 'нас',
  'как', 'что', 'где', 'когда', 'какой', 'какая', 'какое', 'какие', 'сколько', 'почему', 'зачем', 'кто',
  'это', 'то', 'так', 'там', 'тут', 'здесь', 'для', 'или', 'ли', 'же', 'бы', 'ну', 'вот', 'еще', 'тоже', 'уже', 'вообще', 'просто', 'очень',
  'есть', 'можно', 'нужно', 'надо', 'нужен', 'нужна', 'будет', 'быть', 'хочу', 'хотел', 'хотела', 'подскажите', 'скажите', 'вопрос',
  'расскажи', 'расскажите', 'рассказать', 'подскажи', 'скажи',
  'про', 'при', 'на', 'по', 'за', 'из', 'от', 'до', 'с', 'со', 'в', 'во', 'у', 'о', 'об', 'к', 'ко',
])

export function stem(word: string): string {
  let w = word.toLowerCase().replace(/ё/g, 'е')
  for (const [re, root] of synonyms) if (re.test(w)) return root
  w = w.replace(/(ся|сь)$/, '')
  for (const e of endings) {
    if (w.length - e.length >= 3 && w.endsWith(e)) return w.slice(0, -e.length)
  }
  return w
}

export function tokens(text: string): string[] {
  return (text.toLowerCase().replace(/ё/g, 'е').match(/[a-zа-я0-9]+/g) ?? []).filter((t) => t.length >= 2 && !stop.has(t)).map(stem)
}
