// Тексты вопросов (q) у старых id не меняем: по ним ищут ответы помощник и бот

/** 79031537740 → +7 903 153-77-40 */
const whatsappText = contacts.whatsapp.replace(/^7(\d{3})(\d{3})(\d{2})(\d{2})$/, '+7 $1 $2-$3-$4')

/** «а», «а и б», «а, б и в» */
const listAnd = (items: string[]) => (items.length < 2 ? items.join('') : `${items.slice(0, -1).join(', ')} и ${items.at(-1)}`)

const rub = (n: number) => formatRub(n).replace(/\u00A0/g, ' ')
/** «56 000» — число без знака рубля, для вилки «от 56 000 до 70 000 ₽» */
const num = (n: number) => n.toLocaleString('ru-RU').replace(/\s/g, ' ')

/** Отделы оплачиваемой практики в предложном падеже — из вакансий, чтобы список не разошёлся с данными */
const unitIn: Record<string, string> = {
  Лаборатория: 'в лаборатории',
  'Цех розлива': 'в цехе розлива',
  'Технологический цех': 'в технологическом цехе',
  'Складской комплекс': 'на складе',
}
/** Функция, а не константа: администратор может закрыть отдел в панели — список пересчитается при следующем чтении */
const practiceUnits = () => listAnd([...new Set(paidPractice.map((v) => v.unit ?? ''))].filter(Boolean).map((u) => unitIn[u] ?? u.toLowerCase()))

/** Где нужна медкнижка — по тому же правилу, что в форме заявки (needsMedBook) */
