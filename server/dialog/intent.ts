// Разбор свободного текста внутри сценариев: вопрос это или ответ на шаг заявки.
// Правила осторожные: имя «Анна-Мария» или «Иванов Иван Иванович» не должно стать вопросом,
// а «а сколько платят?» — именем.

const norm = (text: string) =>
  text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[«»"“”„]/g, '')
    .replace(/\s+/g, ' ')
    .trim()

const words = (t: string) => t.split(/[^a-zа-я0-9-]+/i).filter(Boolean)

