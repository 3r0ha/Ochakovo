-- Путь кандидата после собеседования (пакет w2-hr-pipeline): напоминание о первой смене, кто отметил согласие,
-- телефон отдела подбора в текстах сообщений — как в «Справочнике студента».

-- ── Напоминание накануне первой смены ─────────────────────────────────────
-- В бот, а кандидатам без бота — SMS, если провайдер подключён. Иначе HR получает задачу «напомнить звонком».
-- Подстановки те же, что у собеседования: {date} и {time} — первая смена, {address} — адрес завода
insert into notify_templates (status, text) values
  ('shift_reminder', '{name}, напоминаем: завтра, {date}, в {time} — первая смена в «Очаково». Адрес: {address}. С собой: паспорт. Если планы изменились, позвони 8 800 100-77-77, доб. 1155, 3105, 2107.'),
  ('sms_shift_reminder', 'Очаково: {name}, завтра в {time} первая смена. Адрес: {address}. Если планы изменились, позвони 88001007777 доб. 1155')
on conflict (status) do nothing;

-- ── Телефон отдела подбора ────────────────────────────────────────────────
-- «Справочник студента»: «связаться с отделом подбора … по телефонам 8 800 100 77 77 (доб 1155, 3105, 2107)».
-- Сайт, бот и Квасыч называют этот номер (shared/content/content.ts, contacts.phone). Меняем только номер:
-- остальной текст, в том числе поправленный администратором, остаётся как был
update notify_templates set text = replace(text, '+7 495 785-39-30, доб. 1155, 2107', '8 800 100-77-77, доб. 1155, 3105, 2107')
  where text like '%+7 495 785-39-30, доб. 1155, 2107%';
update notify_templates set text = replace(text, '+74957853930 доб. 1155', '88001007777 доб. 1155')
  where text like '%+74957853930 доб. 1155%';

-- ── Кто отметил согласие ──────────────────────────────────────────────────
-- Для кандидатов, добавленных сотрудником: «устно» или «отклик на работном сайте». Время — consent_at из 012
alter table applications add column consent_by text not null default '';
