set text = '{name}, напоминаем: завтра, {date}, в {time} — собеседование в «Очаково». Адрес: {address}. С собой: {bring}. Если планы изменились, позвони +7 495 785-39-30, доб. 1155, 2107.',
    updated_at = now()
where status = 'reminder'
  and text = '{name}, напоминаем: завтра собеседование в «Очаково». {date}, {time}, {address}. С собой: {bring}. Если планы изменились, позвони +7 495 785-39-30, доб. 1155, 2107.';
